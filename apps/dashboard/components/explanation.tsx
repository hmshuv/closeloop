import { Badge, Card } from "@/components/ui";
import type { Draft, Explanation } from "@/lib/snapshot";

export function SourceBadge({ e }: { e: Explanation }) {
  if (e.source === "llm") return <Badge tone="violet" title="Generated by a language model from read-only evidence; schema- and evidence-checked">LLM · {e.model ?? "model"}</Badge>;
  if (!e.llm_requested) return <Badge title="The snapshot only requested LLM explanations for the demo cases and the top exceptions">Deterministic template · LLM not used</Badge>;
  return <Badge tone="amber" title="The LLM was asked but its answer was rejected or unavailable">Deterministic fallback · {e.fallback_reason ?? "fallback"}</Badge>;
}

export function ExplanationCard({ e }: { e: Explanation }) {
  return (
    <Card title="Explanation" subtitle="Generated from the read-only evidence below. It never changes a match or a record." action={<SourceBadge e={e} />}>
      <div className="space-y-3 text-sm">
        <p className="font-medium">{e.root_cause}</p>
        <p className="text-zinc-700 dark:text-zinc-300">{e.explanation}</p>
        <div className="rounded-lg bg-zinc-50 p-3 dark:bg-zinc-800/60">
          <div className="text-xs font-medium uppercase tracking-wide text-zinc-500">Recommended action</div>
          <p className="mt-1">{e.recommended_action}</p>
        </div>
        <div className="flex flex-wrap items-center gap-2 text-xs text-zinc-500 dark:text-zinc-400">
          {e.requires_human_review ? <Badge tone="amber">Requires human review</Badge> : <Badge tone="green">No review required</Badge>}
          <span>Confidence {Math.round(e.confidence * 100)}%</span>
          <span>· Cites {e.evidence_ids.length} evidence id{e.evidence_ids.length === 1 ? "" : "s"}, all verified to be in the bundle</span>
        </div>
      </div>
    </Card>
  );
}

export function DraftCard({ d }: { d: Draft }) {
  return (
    <Card title="Draft correcting entry" subtitle={d.narration} action={<Badge tone="amber">Pending approval · never auto-posted</Badge>}>
      <div className="overflow-x-auto">
        <table className="w-full text-sm">
          <thead className="text-left text-xs text-zinc-500 dark:text-zinc-400">
            <tr>
              <th className="py-1 pr-3 font-medium">Account</th>
              <th className="py-1 pr-3 text-right font-medium">Debit</th>
              <th className="py-1 text-right font-medium">Credit</th>
            </tr>
          </thead>
          <tbody className="tabular divide-y divide-zinc-100 dark:divide-zinc-800">
            {d.lines.map((l, i) => (
              <tr key={i}>
                <td className="py-1.5 pr-3">{l.account}</td>
                <td className="py-1.5 pr-3 text-right">{l.debit.amount_paise ? l.debit.amount_inr : ""}</td>
                <td className="py-1.5 text-right">{l.credit.amount_paise ? l.credit.amount_inr : ""}</td>
              </tr>
            ))}
            <tr className="font-semibold">
              <td className="py-1.5 pr-3">Total</td>
              <td className="py-1.5 pr-3 text-right">{d.total_debits.amount_inr}</td>
              <td className="py-1.5 text-right">{d.total_credits.amount_inr}</td>
            </tr>
          </tbody>
        </table>
      </div>
      <p className="mt-3 text-xs text-zinc-500 dark:text-zinc-400">Amounts come from the deterministic engine and always balance. Drafts are stored as pending_approval and are never posted to the ledger.</p>
    </Card>
  );
}
