import type { Dataset } from "../generator/generate.ts";
import { RECON_FIELDS, unixOf, type RazorpayReconItem } from "./razorpay.ts";

export const SYNTHETIC_NOTE = "SYNTHETIC: generated by CloseLoop from its demo dataset. Not real Razorpay data.";

/**
 * A recon report in Razorpay's documented `recon/combined` format, built from a generated dataset: one row per
 * payment and refund in each settlement, with `settlement_utr` set to the UTR of the bank transfer that paid it
 * (a consolidated payout's own UTR, otherwise the settlement's). Every row is labelled synthetic in `notes`.
 */
export function buildSyntheticReconReport(ds: Pick<Dataset, "payments" | "refunds" | "settlements" | "settlementItems" | "payouts">): {
  entity: "collection";
  count: number;
  items: RazorpayReconItem[];
} {
  const payments = new Map(ds.payments.map((p) => [p.id, p]));
  const refunds = new Map(ds.refunds.map((r) => [r.id, r]));
  const payoutUtr = new Map(ds.payouts.flatMap((p) => p.settlement_ids.map((id) => [id, p.utr] as const)));
  const itemsOf = new Map<string, Dataset["settlementItems"]>();
  for (const it of ds.settlementItems) itemsOf.set(it.settlement_id, [...(itemsOf.get(it.settlement_id) ?? []), it]);

  const items: RazorpayReconItem[] = [];
  // Keys in the documented field order, so the file reads like the API's own response.
  const push = (row: Record<string, unknown>) => items.push(Object.fromEntries(RECON_FIELDS.map((f) => [f, row[f] ?? null])) as RazorpayReconItem);
  for (const s of ds.settlements.slice().sort((a, b) => a.created_at.localeCompare(b.created_at) || a.id.localeCompare(b.id))) {
    const common = {
      currency: "INR",
      on_hold: false,
      settled: true,
      settled_at: unixOf(s.created_at),
      settlement_id: s.id,
      posted_at: null,
      credit_type: "default",
      description: null,
      notes: { source: SYNTHETIC_NOTE },
      settlement_utr: payoutUtr.get(s.id) ?? s.utr,
      order_receipt: null,
      card_network: null,
      card_issuer: null,
      card_type: null,
      dispute_id: null,
    };
    for (const it of (itemsOf.get(s.id) ?? []).slice().sort((a, b) => a.id.localeCompare(b.id))) {
      if (it.entity_type === "payment") {
        const p = payments.get(it.entity_id);
        if (!p) continue;
        push({
          entity_id: p.id,
          type: "payment",
          debit: 0,
          credit: it.net_paise,
          amount: it.gross_paise,
          fee: it.fee_paise,
          tax: it.gst_paise,
          created_at: unixOf(p.captured_at),
          payment_id: null,
          order_id: p.order_id,
          method: p.method,
          ...common,
        });
      } else {
        const r = refunds.get(it.entity_id);
        const p = r ? payments.get(r.payment_id) : undefined;
        if (!r || !p) continue;
        push({
          entity_id: r.id,
          type: "refund",
          debit: -it.net_paise,
          credit: 0,
          amount: -it.gross_paise,
          fee: 0,
          tax: 0,
          created_at: unixOf(r.created_at),
          payment_id: r.payment_id,
          order_id: p.order_id,
          method: p.method,
          ...common,
        });
      }
    }
  }
  return { entity: "collection", count: items.length, items };
}

/** The API's collection shape with one item per line, so the committed fixture diffs readably. */
export function reconReportJson(report: { count: number; items: readonly RazorpayReconItem[] }): string {
  return `{"entity":"collection","count":${report.count},"items":[\n${report.items.map((i) => JSON.stringify(i)).join(",\n")}\n]}\n`;
}
