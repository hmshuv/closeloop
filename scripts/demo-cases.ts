/**
 * pnpm demo:cases — picks the demo cases from the October run on the default demo dataset
 * (seed 42, 5,000 payments: the data `closeloop-mcp` seeds on first run) and writes DEMO.md.
 * Nothing here is hand-picked or hardcoded: rerun it after any engine change.
 */
import { writeFileSync } from "node:fs";
import { z } from "zod";
import {
  formatINR,
  generateDataset,
  loadConfig,
  loadDataset,
  openReconDb,
  runReconciliation,
  showcaseCases,
  type BankLine,
  type Settlement,
} from "@closeloop/core";

const SEED = 42;
const PAYMENTS = 5000;
const FROM = "2026-10-01";
const TO = "2026-10-31";

const cfg = loadConfig();
const ds = generateDataset({ seed: SEED, payments: PAYMENTS, config: cfg });
const db = openReconDb(":memory:");
loadDataset(db, null, ds);
const { result, summary } = runReconciliation(db, cfg, { from: FROM, to: TO });
// Same selection the month_end_review MCP prompt uses.
const picks = showcaseCases(db, summary.run_id, FROM, TO);

const lines = new Map(ds.bankLines.map((l) => [l.id, l]));
const settlements = new Map(ds.settlements.map((s) => [s.id, s]));
const line = (id: string) => lines.get(id) as BankLine;
const stl = (id: string) => settlements.get(id) as Settlement;
const settlementRows = (ids: string[]) =>
  ["| Settlement | UTR | Settled | Amount |", "|---|---|---|---|", ...ids.map((id) => stl(id)).sort((a, b) => a.created_at.localeCompare(b.created_at)).map((s) => `| \`${s.id}\` | \`${s.utr}\` | ${s.settled_at} | ${formatINR(s.amount_paise)} |`)].join("\n");
const lineBlock = (l: BankLine) => `- Bank line \`${l.id}\` · ${l.txn_date} · credit **${formatINR(l.credit_paise)}**\n- Narration: \`${l.narration}\``;

// 1. Largest contiguous batch credit in October (by number of settlements, then amount).
const batchLineId = picks.largestContiguousBatch?.bank_line_id;
const batchMatches = result.matches.filter((m) => m.kind === "BATCH_CONTIGUOUS" && m.right.id === batchLineId);
if (!batchLineId || batchMatches.length === 0) throw new Error("No contiguous batch credit in October");

// 2. A fuzzy auto-match in October (prefer a genuine edit-distance-1 typo).
const fuzzy = result.matches.find((m) => m.kind === "FUZZY" && m.right.id === picks.fuzzyMatch?.bank_line_id);
if (!fuzzy) throw new Error("No fuzzy match in October");
const fuzzyBest = fuzzy.trace.best as { token: string; distance: number; confidence: number };
const fuzzyRunner = fuzzy.trace.runner_up as { settlement_id: string; distance: number | null } | null;

// 3. A MATCH_CONFLICT in October.
const conflict = result.exceptions.find((e) => e.type === "MATCH_CONFLICT" && e.primary.id === picks.matchConflict?.bank_line_id);
if (!conflict) throw new Error("No MATCH_CONFLICT in October");
const ct = z
  .object({ batch_settlement_ids: z.array(z.string()), conflicting_settlement_ids: z.array(z.string()), suggested_on_bank_lines: z.array(z.string()) })
  .parse(conflict.trace);

const md = `# Demo cases (October 2026)

Generated by \`pnpm demo:cases\` from an actual run (${FROM} → ${TO}) on the default demo dataset: seed ${SEED}, ${PAYMENTS.toLocaleString("en-IN")} payments. That is the same data \`npx closeloop-mcp\` seeds on first run. The record IDs are stable for this seed. Run IDs and exception IDs are new on every run, so look those up via the tools.

## 1. Largest contiguous batch credit: one bank credit, ${batchMatches.length} settlements

${lineBlock(line(batchLineId))}
- Match kind \`BATCH_CONTIGUOUS\`: the ${batchMatches.length} settlements are consecutive in time (by \`created_at\`) and sum exactly to the credit.
- The trace states the assumption: *unique among contiguous runs only (payout model), not proof that no other subset sums to it.* Arbitrary-subset check: \`${String(batchMatches[0]?.trace.arbitrary_subset_search)}\`.

${settlementRows(batchMatches.map((m) => m.left.id))}

**Ask Claude:** "Break down bank credit ${batchLineId}." · "Why is this matched as contiguous rather than proven unique?"

## 2. Fuzzy match: corrupted UTR recovered deterministically

${lineBlock(line(fuzzy.right.id))}
- Matched to settlement \`${fuzzy.left.id}\` (UTR \`${stl(fuzzy.left.id).utr}\`, ${formatINR(stl(fuzzy.left.id).amount_paise)}, settled ${stl(fuzzy.left.id).settled_at}).
- Evidence: narration token \`${fuzzyBest.token}\` is edit distance **${fuzzyBest.distance}** from the UTR. Exact amount and the date window are hard requirements, and both hold. Runner-up: ${fuzzyRunner ? `\`${fuzzyRunner.settlement_id}\` (distance ${fuzzyRunner.distance ?? "truncated"})` : "none"}; margin ${String(fuzzy.trace.margin)}.
- Displayed confidence ${fuzzyBest.confidence} (display only; the threshold is the edit distance).

**Ask Claude:** "How was ${fuzzy.right.id} matched if the UTR in the narration is wrong?"

## 3. MATCH_CONFLICT: the engine refuses to guess

${lineBlock(line(conflict.primary.id))}
- The only subset that sums to this credit includes settlement \`${ct.conflicting_settlement_ids.join(", ")}\`, which already has a pending SUGGESTED_MATCH from bank line \`${ct.suggested_on_bank_lines.join(", ")}\` (a look-alike UTR with the same amount).
- Neither the batch nor the suggestion is auto-matched; both go to a human.

${settlementRows(ct.batch_settlement_ids)}

Decoy credit:

${ct.suggested_on_bank_lines.map((id) => lineBlock(line(id))).join("\n\n")}

**Ask Claude:** "Show me the match conflicts in October and what you'd need from me to resolve them."

## Opening questions

- "What's unreconciled in October and why?"
- "Break down the largest unmatched bank credit."
`;
writeFileSync("DEMO.md", md);
console.log(md);
