/**
 * pnpm eval [--payments N] [--seeds 101,202] [--min-per-type 15] [--write | --no-write]
 *
 * Full run (default config size): consumes the fixed seed list until every held-out target has enough
 * truth labels, writes EVAL.md and the README Results block, and fails if coverage is still short.
 * Smoke run (`--payments 5000`, used by CI): same pipeline, reports coverage shortfalls as warnings and
 * does not overwrite EVAL.md unless --write is passed.
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { loadConfig } from "@closeloop/core";
import { gatewayComparison, headline, renderEvalMarkdown, renderReadmeResults, runEval } from "@closeloop/core/eval";

const cfg = loadConfig();
const g = cfg.generator;
const { values } = parseArgs({
  options: {
    payments: { type: "string" },
    seeds: { type: "string" },
    "min-per-type": { type: "string" },
    write: { type: "boolean" },
    "no-write": { type: "boolean" },
  },
});
const payments = values.payments ? Number(values.payments) : g.eval_payments;
if (!Number.isSafeInteger(payments) || payments <= 0) throw new Error(`--payments must be a positive integer`);
const full = payments === g.eval_payments && !values.seeds;
const seeds = values.seeds ? values.seeds.split(",").map(Number) : g.eval_seeds;
const minPerType = values["min-per-type"] ? Number(values["min-per-type"]) : g.heldout_min_per_type;
const write = values["no-write"] ? false : (values.write ?? full);

const result = runEval({
  cfg,
  payments,
  days: g.days,
  seeds,
  minPerType,
  sweep: { payments: [5_000, 12_500, 25_000], seeds: g.eval_seeds.slice(0, 2) },
});

const H = headline(result, "heldout");
const D = headline(result, "dev");
const p = (n: number, d: number) => (d ? `${((100 * n) / d).toFixed(1)}%` : "—");
console.log(`CloseLoop eval — ${result.seedsUsed.length} seed(s) × ${payments} payments, ${(result.totalMs / 1000).toFixed(1)} s`);
console.table({
  dev: { credits_correct: p(...D.credits), wrong_links: D.wrongLinks, fuzzy_recovered: p(...D.fuzzy), batch_correct: p(...D.batch), batch_ambiguous: p(...D.batchAmbiguous), macro_recall: p(D.macroRecall, 1), macro_precision: p(D.macroPrecision, 1) },
  heldout: { credits_correct: p(...H.credits), wrong_links: H.wrongLinks, fuzzy_recovered: p(...H.fuzzy), batch_correct: p(...H.batch), batch_ambiguous: p(...H.batchAmbiguous), macro_recall: p(H.macroRecall, 1), macro_precision: p(H.macroPrecision, 1) },
});
const G = gatewayComparison(result);
console.log("Held-out, amount-only vs with gateway recon report:");
console.table({
  amount_only: { batch_correct: p(G.amount_only.batch.correct, G.amount_only.batch.n), ambiguous: G.amount_only.batch.ambiguous, conflicts: G.amount_only.batch.conflict, wrong_links: G.amount_only.credits.wrong_links, unresolved_in_batch: G.amount_only.unresolved_in_batch },
  with_report: { batch_correct: p(G.with_report.batch.correct, G.with_report.batch.n), ambiguous: G.with_report.batch.ambiguous, conflicts: G.with_report.batch.conflict, wrong_links: G.with_report.credits.wrong_links, unresolved_in_batch: G.with_report.unresolved_in_batch },
});
if (result.shortfall.length) console.log(`Held-out coverage below ${minPerType}: ${result.shortfall.map((c) => `${c.target}=${c.count}`).join(", ")}`);

if (write) {
  const commit = (() => {
    try {
      const sha = execSync("git rev-parse --short HEAD", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
      const dirty = execSync("git status --porcelain --untracked-files=no", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim().length > 0;
      return dirty ? `${sha}-dirty` : sha;
    } catch {
      return null;
    }
  })();
  const command = `pnpm eval${values.payments ? ` --payments ${payments}` : ""}${values.seeds ? ` --seeds ${values.seeds}` : ""}`;
  const generatedAt = new Date().toISOString();
  writeFileSync("EVAL.md", renderEvalMarkdown(result, { generatedAt, commit, command }) + "\n");
  // Machine-readable headline from the same run, for the dashboard snapshot.
  const evalJson = {
    generated_at: generatedAt,
    commit,
    command,
    seeds_used: result.seedsUsed,
    payments_per_dataset: payments,
    days: g.days,
    runtime_s: Number((result.totalMs / 1000).toFixed(1)),
    coverage_met: result.shortfall.length === 0,
    dev: D,
    heldout: H,
    gateway_report_vs_amount_only: { split: "heldout", ...G },
    batch_by_volume: result.sweep.map((s) => ({ payments: s.payments, payments_per_day: s.payments_per_day, max_pool: s.max_pool, outcomes: s.score.batch })),
  };
  writeFileSync("EVAL.json", JSON.stringify(evalJson, null, 2) + "\n");
  const readme = readFileSync("README.md", "utf8");
  const block = `<!-- results:start (generated by pnpm eval; do not edit) -->\n${renderReadmeResults(result)}\n<!-- results:end -->`;
  const updated = readme.replace(/<!-- results:start[\s\S]*?<!-- results:end -->/, block);
  if (updated === readme && !readme.includes("<!-- results:start")) console.log("README has no results markers; skipped README update.");
  else writeFileSync("README.md", updated);
  console.log("Wrote EVAL.md, EVAL.json and the README Results block.");
}

if (full && result.shortfall.length) {
  console.error("Coverage minimum not met with the fixed seed list. Increase eval_payments or add seeds; never inflate noise rates.");
  process.exit(1);
}
